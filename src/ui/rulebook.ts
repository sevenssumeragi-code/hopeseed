import { DB } from "../dataLoader.js";

export interface RulebookLive {
  fireLeft?: number;
  waterLeft?: number;
  reviveIn?: number;
}

export function rulebookText(live?: RulebookLive): string {
  const c = DB.config;
  const fireNow = live?.fireLeft !== undefined ? `　★現在: あと${live.fireLeft}日` : "";
  const waterNow = live?.waterLeft !== undefined ? `　★現在: あと${live.waterLeft}日` : "";
  const reviveNow = live?.reviveIn === undefined ? ""
    : live.reviveIn <= 0 ? "　★現在: 祈り可能" : `　★現在: あと${live.reviveIn}日で祈り可能`;

  return `——${c.ISLAND_NAME} 生存の手引き——

【① ホープシードの掟】
・保持者が生きている限り、仲間は死んでも蘇生できる（湖の女神の祠で${c.revive.cooldown_days}日に1人）。
・保持者が「死亡」「誘拐」「悪魔に取り憑かれる」と、その瞬間すべてが終わる。
・保持者は最初に選んだら最後まで変わらない。
・保持者は戦いで「攻撃」「技」「魔術」を使えない（防御・庇う・アイテム・逃げるは可能）。
・マップでみんなを導くのは保持者の役目。

【② 3つのフェーズ】
・マップ移動：保持者を操作して島を歩く。敵に触れると戦闘、キラキラで採取。
・戦闘：ターン制。開始時に最大${c.BATTLE_MEMBERS_MAX}人を選んで出撃（保持者の参加は任意）。
・拠点：調理・工作・薬草開発・治療・看病・会話・休息。作業1回＝1時間帯。

【③ 時間と日数】
・1日は 朝・昼・夕・夜 の4つの時間帯。移動や作業で時間が進む。
・移動コストは道のり次第（拠点⇔森は一歩。拠点→火山山頂はほぼ1日仕事）。
・夜は悪魔が現れる（荒野・草原・砂浜）。ヒュウの技は夜に冴える。
・潮汐：朝・昼＝干潮／夕・夜＝満潮。満潮の浅瀬は長居すると波に呑まれる。

【④ 供物の掟】
・炎の女神（火山山頂）：${c.tribute.fire_interval_days}日に一度、動物の肉を。怠れば噴火で全滅。${fireNow}
・水の女神（海の祠）：${c.tribute.water_interval_days}日に一度、魚を。怠れば島水没で全滅。${waterNow}
・ジンパチ保持者は炎、レニィ保持者は水の参拝が${c.tribute.grace_interval_days}日に一度でよい。
・肉と魚は食料と共用——「食べるか、供えるか」。

【⑤ 戦闘の基本】
・行動順は素早さの降順。防御は被ダメージ半減＋終了時SP+${c.guard.sp_recover}。
・庇う：成功率50+技量×0.3+ペア信頼度×0.3。成功すれば一撃必殺も誘拐も取り憑きも防げる。
・逃げる：50+(レベル差)×3%。ボスからは逃げられない。
・ジンパチは獣を手なずけられる（非保持者時）。

【⑥ 状態異常と放置死】
・毒　　：放置${c.status_timers.poison_death_days}日で死。解毒剤で治る。
・大火傷：放置${c.status_timers.burn_death_days}日で死。攻撃と技量が鈍る。火傷薬で治る。
・大出血：放置${c.status_timers.bleed_death_days}日で死。攻撃コマンド不可。拠点の「治療」でのみ止血できる。
・疫病　：蚊が媒介。${c.status_timers.plague_severe_from_day}日目から重症化の危険。疫病薬で治る。
・しびれ：行動失敗のほか、火山や満潮の浅瀬を歩くと${Math.round(c.status_timers.paralysis_move_death * 100)}%で命を落とす。
・感染症：雨天の野宿などで発症。看病で重症化を防げる。抗感染症薬が切り札。
・昏睡　：夢魔に敗れると3〜5日眠り続ける。薬はない。
・肥満　：かろうじて食べれる物の食べ過ぎ。素早さ半減。肥満薬か7日間の粗食で解消。

【⑦ 死亡・誘拐・蘇生】
・戦闘不能のまま戦いが終わると死亡が確定する。
・海賊は倒れた仲間をさらう（庇っていれば防げる）。海賊船の最深部で船長を倒せば全員戻る。
・湖の祠で${c.revive.cooldown_days}日に1人蘇生できる。レベル・技・持ち物・絆はそのまま。${reviveNow}

【⑧ 信頼度と庇う】
・共に戦い、庇い、食卓を囲むほど絆は深まる。
・庇った回数が積み重なると、ふたりだけの特別な会話が生まれる（3・7・15回）。
・ムニが保持者なら、すべての絆が深まりやすい（×1.5）。

【⑨ クラフト】
・調理／工作／薬草開発。作業する人の適性で成功率が変わる。
・大成功＝おいしい料理・素材の節約・薬2倍。失敗＝素材を失う（料理だけは失敗しても食べられる）。
・料理は${c.craft.food_expire_days}日で傷む。作りすぎに注意。
・薬草はそのままでは使えない。調合して初めて薬になる。
・雨の日は外に出られないぶん、作業がはかどる（+5%）。

【⑩ セーブについて】
・就寝時・移動時・戦闘後・ボス戦直前に自動でセーブされる（3世代）。
・手動セーブは10スロット。
・ゲームオーバーになっても、直前のオートセーブから再開できる（最大で1日分の巻き戻し）。
これが${c.ISLAND_NAME}の掟。${c.DAY_MAX}日を生き延びれば、きっと道は開ける。
（新たな脅威が現れるたび、この手引きは書き足されていく）`;
}
